// -----------------------------------------------------------------------------
// SplineMeshGeneratedMeshPersistenceGuard.cs
// Unity 6 / Editor only
// Purpose: Exclude dynamically rebuilt, scene-embedded MeshBender output meshes
//          from scene/build serialization without modifying the SplineMesh asset.
// Place in Assets/Editor/. Do not put this file in a runtime assembly.
// -----------------------------------------------------------------------------

#if UNITY_EDITOR
using System;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.SceneManagement;

/// <summary>
/// SplineMeshTiling の動的生成 Mesh が Scene に埋め込まれることを防止します。
/// 自動保護は初期状態で無効です。検証後、メニューから明示的に有効化します。
/// </summary>
[InitializeOnLoad]
public static class SplineMeshGeneratedMeshPersistenceGuard
{
    private const string MENU_ROOT = "Tools/SplineMesh/Generated Mesh/";
    private const string INSPECT_MENU = MENU_ROOT + "Inspect Active Scene";
    private const string MARK_MENU = MENU_ROOT + "Exclude From Scene (Active Scene)";
    private const string AUTO_GUARD_MENU = MENU_ROOT + "Enable Save Guard";
    private const string GENERATED_MESH_PREFIX = "Generated by ";
    private const string PREFS_KEY_PREFIX = "SplineMesh.GeneratedMeshSaveGuard.Enabled.";

    private static readonly HideFlags EXCLUSION_FLAGS =
        HideFlags.DontSaveInEditor | HideFlags.DontSaveInBuild;

    // プロジェクトごとにEditorPrefsを分離するためのキー。
    private static string EditorPrefsKey => PREFS_KEY_PREFIX + Application.dataPath;

    /// <summary>
    /// Editor の Scene 保存イベントを購読します。
    /// </summary>
    static SplineMeshGeneratedMeshPersistenceGuard()
    {
        EditorSceneManager.sceneSaving += HandleSceneSaving;
        EditorApplication.delayCall += RefreshMenuCheck;
    }

    /// <summary>
    /// 現在の Scene に存在する対象 Mesh を調査し、Console に結果を出力します。
    /// </summary>
    [MenuItem(INSPECT_MENU)]
    private static void InspectActiveScene()
    {
        Scene scene = SceneManager.GetActiveScene();
        if (!IsSupportedScene(scene))
        {
            Debug.LogWarning("[SplineMesh Guard] 保存済みの .unity Scene を開いてください。");
            return;
        }

        ScanResult result = ScanScene(scene, false);
        LogResult(scene, result, "Inspection");
    }

    /// <summary>
    /// 現在の Scene 内にある再生成可能な Mesh に保存除外フラグを付与します。
    /// 実際の Scene 保存はユーザーが行います。
    /// </summary>
    [MenuItem(MARK_MENU)]
    private static void ExcludeFromActiveScene()
    {
        if (Application.isPlaying)
        {
            Debug.LogWarning("[SplineMesh Guard] Play Mode を終了してから実行してください。");
            return;
        }

        Scene scene = SceneManager.GetActiveScene();
        if (!IsSupportedScene(scene))
        {
            Debug.LogWarning("[SplineMesh Guard] 保存済みの .unity Scene を開いてください。");
            return;
        }

        ScanResult result = ScanScene(scene, true);
        if (result.ModifiedMeshCount > 0)
        {
            EditorSceneManager.MarkSceneDirty(scene);
        }

        LogResult(scene, result, "Applied");
        Debug.Log("[SplineMesh Guard] 次に Ctrl+S で Scene を保存し、YAML 容量を再計測してください。");
    }

    /// <summary>
    /// Scene 保存直前にフラグを付ける保護機能を切り替えます。
    /// </summary>
    [MenuItem(AUTO_GUARD_MENU)]
    private static void ToggleSaveGuard()
    {
        bool enabled = !EditorPrefs.GetBool(EditorPrefsKey, false);
        EditorPrefs.SetBool(EditorPrefsKey, enabled);
        Menu.SetChecked(AUTO_GUARD_MENU, enabled);
        Debug.Log($"[SplineMesh Guard] Save Guard: {(enabled ? "Enabled" : "Disabled")}");
    }

    /// <summary>
    /// 自動保護メニューのチェックを更新します。
    /// </summary>
    [MenuItem(AUTO_GUARD_MENU, true)]
    private static bool ValidateSaveGuardMenu()
    {
        RefreshMenuCheck();
        return true;
    }

    private static void RefreshMenuCheck()
    {
        Menu.SetChecked(AUTO_GUARD_MENU, EditorPrefs.GetBool(EditorPrefsKey, false));
    }

    /// <summary>
    /// 有効化されている場合だけ、保存直前の Scene を検査して保存除外します。
    /// </summary>
    private static void HandleSceneSaving(Scene scene, string path)
    {
        if (Application.isPlaying || !EditorPrefs.GetBool(EditorPrefsKey, false))
        {
            return;
        }

        if (!IsSupportedScene(scene))
        {
            return;
        }

        ScanResult result = ScanScene(scene, true);
        if (result.ModifiedMeshCount > 0)
        {
            LogResult(scene, result, "Save Guard");
        }
    }

    private static bool IsSupportedScene(Scene scene)
    {
        return scene.IsValid() && scene.isLoaded &&
               !string.IsNullOrEmpty(scene.path) &&
               scene.path.EndsWith(".unity", StringComparison.OrdinalIgnoreCase);
    }

    /// <summary>
    /// MeshBender の出力Meshだけを対象にします。
    /// ・AssetDatabase に保存済みの Mesh Asset は変更しません。
    /// ・Tiling が Play Mode で再生成しない場合は除外しません。
    /// ・Mesh の頂点情報や GameObject 自体は変更しません。
    /// </summary>
    private static ScanResult ScanScene(Scene scene, bool apply)
    {
        ScanResult result = new ScanResult();

        GameObject[] roots = scene.GetRootGameObjects();
        foreach (GameObject root in roots)
        {
            SplineMesh.MeshBender[] benders =
                root.GetComponentsInChildren<SplineMesh.MeshBender>(true);

            foreach (SplineMesh.MeshBender bender in benders)
            {
                result.MeshBenderCount++;

                if (bender == null || !bender.enabled)
                {
                    result.SkippedCount++;
                    continue;
                }

                // Update In Play Mode が有効な Tiling だけ処理します。
                SplineMesh.SplineMeshTiling tiling =
                    bender.GetComponentInParent<SplineMesh.SplineMeshTiling>(true);

                if (tiling == null || !tiling.enabled || !tiling.updateInPlayMode)
                {
                    result.SkippedCount++;
                    continue;
                }

                MeshFilter meshFilter = bender.GetComponent<MeshFilter>();
                Mesh mesh = meshFilter != null ? meshFilter.sharedMesh : null;

                if (mesh == null ||
                    !mesh.name.StartsWith(GENERATED_MESH_PREFIX, StringComparison.Ordinal) ||
                    AssetDatabase.Contains(mesh))
                {
                    result.SkippedCount++;
                    continue;
                }

                result.EligibleMeshCount++;

                if ((mesh.hideFlags & EXCLUSION_FLAGS) == EXCLUSION_FLAGS)
                {
                    result.AlreadyExcludedCount++;
                    continue;
                }

                if (apply)
                {
                    mesh.hideFlags |= EXCLUSION_FLAGS;
                    result.ModifiedMeshCount++;
                }
            }
        }

        return result;
    }

    private static void LogResult(Scene scene, ScanResult result, string label)
    {
        Debug.Log(
            $"[SplineMesh Guard] {label} - {scene.path}\n" +
            $"MeshBender: {result.MeshBenderCount}, " +
            $"Eligible: {result.EligibleMeshCount}, " +
            $"Already excluded: {result.AlreadyExcludedCount}, " +
            $"Modified: {result.ModifiedMeshCount}, " +
            $"Skipped: {result.SkippedCount}");
    }

    private struct ScanResult
    {
        public int MeshBenderCount;
        public int EligibleMeshCount;
        public int AlreadyExcludedCount;
        public int ModifiedMeshCount;
        public int SkippedCount;
    }
}
#endif
